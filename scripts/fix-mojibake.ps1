$files = @(
  "frontend/public/home-content.html",
  "frontend/index.html",
  "AGENTS.md",
  "QWEN.md",
  "README.md"
)

function s([int[]]$codes) { return ($codes | ForEach-Object { [char]$_ }) -join '' }

$map = [ordered]@{
  (s 0x00C4,0x00B1) = [char]0x0131
  (s 0x00C4,0x00B0) = [char]0x0130
  (s 0x00C5,0x00BF) = [char]0x015F
  (s 0x00C5,0x00BD) = [char]0x015E
  (s 0x00C4,0x00BF) = [char]0x011F
  (s 0x00C4,0x009E) = [char]0x011E
  (s 0x00C3,0x00A7) = [char]0x00E7
  (s 0x00C3,0x0087) = [char]0x00C7
  (s 0x00C3,0x00BC) = [char]0x00FC
  (s 0x00C3,0x009C) = [char]0x00DC
  (s 0x00C3,0x00B6) = [char]0x00F6
  (s 0x00C3,0x0096) = [char]0x00D6
  (s 0x00C3,0x00B1) = [char]0x00F1
  (s 0x00C4,0x0178) = [char]0x011F
  (s 0x00C4,0x017D) = [char]0x011E
  (s 0x00C5,0x0178) = [char]0x015F
  (s 0x00C5,0x017D) = [char]0x015E
  (s 0x00C3,0x2013) = [char]0x00D6
  (s 0x00C3,0x0153) = [char]0x00DC
  (s 0x00E2,0x0080,0x0099) = [char]0x2019
  (s 0x00E2,0x0080,0x009C) = [char]0x201C
  (s 0x00E2,0x0080,0x009D) = [char]0x201D
  (s 0x00E2,0x0080,0x0093) = [char]0x2013
  (s 0x00E2,0x0080,0x0094) = [char]0x2014
  (s 0x00E2,0x0080,0x00A6) = [char]0x2026
  (s 0x00E2,0x20AC,0x2122) = [char]0x2019
  (s 0x00E2,0x20AC,0x0153) = [char]0x201C
  (s 0x00E2,0x20AC,0x009D) = [char]0x201D
  (s 0x00E2,0x20AC,0x201D) = [char]0x2014
  (s 0x00C2) = ''
}

foreach ($file in $files) {
  if (-not (Test-Path $file)) { Write-Host "Missing $file"; continue }
  $text = Get-Content -Raw -Path $file
  foreach ($k in $map.Keys) {
    $text = $text.Replace($k, $map[$k])
  }
  Set-Content -Encoding UTF8 -Path $file -Value $text
}
